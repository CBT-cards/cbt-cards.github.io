def fail(message: str) -> None:
    raise SystemExit(f"localized page build failed: {message}")


def load_jsonl(path: Path) -> list[dict]:
    records: list[dict] = []
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError as exc:
            fail(f"invalid JSONL in {path.relative_to(ROOT)} line {line_number}: {exc}")
        if not isinstance(record, dict):
            fail(f"non-object JSONL record in {path.relative_to(ROOT)} line {line_number}")
        records.append(record)
    return records


def is_published(record: dict) -> bool:
    return (
        record.get("translation_status") == "human_reviewed"
        and record.get("review_status") == "reviewed_for_publication"
        and record.get("publication_status") == "published"
    )


def expected_canonical(locale: str, resource_id: str) -> str:
    return f"{ORIGIN}/{locale}/resources/{resource_id}/"


def local_path_from_url(url: str) -> Path:
    parsed = urlparse(url)
    if f"{parsed.scheme}://{parsed.netloc}" != ORIGIN:
        fail(f"localized canonical is outside CBT Cards origin: {url}")
    if not parsed.path.endswith("/"):
        fail(f"localized canonical must end with '/': {url}")
    return ROOT / parsed.path.lstrip("/") / "index.html"


def esc(value: object) -> str:
    return html.escape(str(value), quote=True)


